-- The same tables as the SQLite store's, with integrity rules only: keys,
-- CHECKs, uniqueness, the append-only audit log, and row-level security
-- keyed on the ledger set for each transaction (SET LOCAL, so it never
-- leaks across pooled connections). Amounts are NUMERIC integers with a
-- count of places; text is compared by its bytes (COLLATE "C").

CREATE TABLE users (
    id            bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name  text    COLLATE "C" NOT NULL,
    password_hash text,
    is_admin      boolean NOT NULL DEFAULT false,
    created_at    text    NOT NULL
);

CREATE TABLE identities (
    provider text   COLLATE "C" NOT NULL,
    subject  text   COLLATE "C" NOT NULL,
    user_id  bigint NOT NULL REFERENCES users (id),
    PRIMARY KEY (provider, subject)
);

CREATE INDEX identities_user ON identities (user_id);

CREATE TABLE ledgers (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text   NOT NULL,
    revision            bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at          text   NOT NULL,
    next_transaction_id bigint NOT NULL DEFAULT 1 CHECK (next_transaction_id >= 1)
);

CREATE TABLE memberships (
    ledger_id bigint NOT NULL REFERENCES ledgers (id) ON DELETE CASCADE,
    user_id   bigint NOT NULL REFERENCES users (id),
    role      text   NOT NULL CHECK (role IN ('read', 'write', 'rewrite')),
    PRIMARY KEY (ledger_id, user_id)
);

CREATE INDEX memberships_user ON memberships (user_id);

CREATE TABLE accounts (
    ledger_id     bigint NOT NULL REFERENCES ledgers (id) ON DELETE CASCADE,
    name          text   COLLATE "C" NOT NULL CHECK (name <> ''),
    declared_tags text   NOT NULL DEFAULT '',
    PRIMARY KEY (ledger_id, name)
);

CREATE TABLE commodities (
    ledger_id    bigint  NOT NULL REFERENCES ledgers (id) ON DELETE CASCADE,
    symbol       text    COLLATE "C" NOT NULL,
    style_side   text    NOT NULL DEFAULT 'left' CHECK (style_side IN ('left', 'right')),
    style_space  boolean NOT NULL DEFAULT false,
    decimal_mark text    NOT NULL DEFAULT '.' CHECK (decimal_mark IN ('.', ',')),
    group_mark   text    NOT NULL DEFAULT '',
    group_sizes  text    NOT NULL DEFAULT '',
    places       integer CHECK (places IS NULL OR places BETWEEN 0 AND 255),
    PRIMARY KEY (ledger_id, symbol)
);

CREATE TABLE transactions (
    ledger_id        bigint NOT NULL REFERENCES ledgers (id) ON DELETE CASCADE,
    id               bigint NOT NULL CHECK (id > 0),
    date             date   NOT NULL,
    status           text   NOT NULL DEFAULT 'unmarked'
                            CHECK (status IN ('unmarked', 'pending', 'cleared')),
    code             text   NOT NULL DEFAULT '',
    description      text   NOT NULL DEFAULT '',
    comment          text   NOT NULL DEFAULT '',
    revision_created bigint NOT NULL CHECK (revision_created >= 1),
    revision_changed bigint NOT NULL CHECK (revision_changed >= revision_created),
    PRIMARY KEY (ledger_id, id)
);

CREATE INDEX transactions_by_date ON transactions (ledger_id, date, id);

CREATE TABLE postings (
    ledger_id        bigint   NOT NULL,
    transaction_id   bigint   NOT NULL,
    position         integer  NOT NULL CHECK (position >= 0),
    account          text     COLLATE "C" NOT NULL,
    kind             text     NOT NULL DEFAULT 'real'
                              CHECK (kind IN ('real', 'virtual', 'balanced_virtual')),
    status           text     NOT NULL DEFAULT 'unmarked'
                              CHECK (status IN ('unmarked', 'pending', 'cleared')),
    mantissa         numeric  NOT NULL CHECK (scale(mantissa) = 0),
    places           smallint NOT NULL CHECK (places BETWEEN 0 AND 255),
    commodity        text     COLLATE "C" NOT NULL,
    cost_kind        text     CHECK (cost_kind IN ('unit', 'total')),
    cost_mantissa    numeric  CHECK (scale(cost_mantissa) = 0),
    cost_places      smallint CHECK (cost_places BETWEEN 0 AND 255),
    cost_commodity   text     COLLATE "C",
    assert_op        text     CHECK (assert_op IN ('=', '==', '=*', '==*')),
    assert_mantissa  numeric  CHECK (scale(assert_mantissa) = 0),
    assert_places    smallint CHECK (assert_places BETWEEN 0 AND 255),
    assert_commodity text     COLLATE "C",
    comment          text     NOT NULL DEFAULT '',
    PRIMARY KEY (ledger_id, transaction_id, position),
    FOREIGN KEY (ledger_id, transaction_id)
        REFERENCES transactions (ledger_id, id) ON DELETE CASCADE,
    -- Checked at commit, so deleting a ledger can take its accounts and
    -- its postings in either order.
    FOREIGN KEY (ledger_id, account) REFERENCES accounts (ledger_id, name)
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (ledger_id, commodity) REFERENCES commodities (ledger_id, symbol)
        DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (ledger_id, cost_commodity) REFERENCES commodities (ledger_id, symbol)
        DEFERRABLE INITIALLY DEFERRED,
    CHECK ((cost_kind IS NULL) = (cost_mantissa IS NULL)
       AND (cost_kind IS NULL) = (cost_places IS NULL)
       AND (cost_kind IS NULL) = (cost_commodity IS NULL)),
    CHECK ((assert_op IS NULL) = (assert_mantissa IS NULL)
       AND (assert_op IS NULL) = (assert_places IS NULL)
       AND (assert_op IS NULL) = (assert_commodity IS NULL))
);

CREATE INDEX postings_by_account ON postings (ledger_id, account);

CREATE TABLE audit_log (
    ledger_id bigint  NOT NULL REFERENCES ledgers (id) ON DELETE CASCADE,
    revision  bigint  NOT NULL CHECK (revision >= 1),
    n         integer NOT NULL CHECK (n >= 0),
    user_id   bigint  NOT NULL REFERENCES users (id),
    actor     text    NOT NULL,
    kind      text    NOT NULL,
    summary   text    NOT NULL,
    payload   json    NOT NULL,
    PRIMARY KEY (ledger_id, revision, n)
);

-- Single rows are never rewritten. A ledger's rows go with the ledger.
CREATE FUNCTION audit_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM ledgers WHERE id = OLD.ledger_id) THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$;

CREATE TRIGGER audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();

-- Row-level security: a transaction sees one ledger's rows, the one it
-- set, unless it is one of the server's own operations across ledgers.
ALTER TABLE ledgers ENABLE ROW LEVEL SECURITY;
ALTER TABLE ledgers FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant ON ledgers
    USING (id = NULLIF(current_setting('kabacus.ledger', true), '')::bigint
           OR current_setting('kabacus.scope', true) = 'all')
    WITH CHECK (id = NULLIF(current_setting('kabacus.ledger', true), '')::bigint
           OR current_setting('kabacus.scope', true) = 'all');

